#!/usr/bin/env python3
"""Write references/principles-index.md: one line per principle (stdlib).

The full registry (references/principles.json) is about 65K tokens and must
never be loaded whole at runtime. This index is about 8K tokens and holds the
fields an agent needs to pick a card: id, title, kind, tags, first trigger,
and the dossier path. Use `coverage.py show <ID>` for the full card.

Usage: python3 scripts/principles_index.py [--check]
--check exits 1 when the committed index is stale.
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / 'references/principles.json'
INDEX = ROOT / 'references/principles-index.md'


def render():
    data = json.loads(REGISTRY.read_text())
    rows = []
    for p in data['principles']:
        trigger = (p.get('triggers') or [''])[0].strip()
        if len(trigger) > 110:
            trigger = trigger[:107].rstrip() + '...'
        rows.append('| {id} | {title} | {kind} | {tags} | {trigger} | `{path}` |'.format(
            id=p['id'], title=p['title'], kind=p.get('kind', ''),
            tags=' '.join(p.get('tags', [])), trigger=trigger.replace('|', '/'),
            path=p['source']['path'].replace('references/', '')))
    head = ('# Principles index\n\n'
            'Generated by `scripts/principles_index.py` from `principles.json`. '
            'Do not edit by hand. One line per principle. Run '
            '`coverage.py show <ID>` for the full card with rationale, '
            'exceptions, and locators.\n\n'
            '| ID | Title | Kind | Tags | First trigger | Dossier |\n'
            '|---|---|---|---|---|---|\n')
    return head + '\n'.join(rows) + '\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    text = render()
    if args.check:
        if not INDEX.exists() or INDEX.read_text() != text:
            print('principles-index.md is stale; run scripts/principles_index.py')
            return 1
        print('principles-index.md is current')
        return 0
    INDEX.write_text(text)
    print(f'wrote {INDEX.relative_to(ROOT)} ({text.count(chr(10)) - 6} principles)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
